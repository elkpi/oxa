import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const check = process.argv.slice(2).join(" ") === "--check";
const tsRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(tsRoot, "..");
const schemas = [
  ["ir", "Ir"],
  ["loss", "Loss"],
  ["vector", "Vector"],
];

let stale = false;
for (const [name, prefix] of schemas) {
  const source = resolve(repoRoot, "spec/schema", `${name}.schema.json`);
  const output = resolve(tsRoot, "src/generated", `${name}-schema.ts`);
  const document = JSON.parse(readFileSync(source, "utf8"));
  const sourcePath = relative(repoRoot, source).replaceAll("\\", "/");
  const generated = render(document, prefix, sourcePath);
  if (check) {
    let actual;
    try {
      actual = readFileSync(output, "utf8");
    } catch {
      actual = undefined;
    }
    if (actual !== generated) {
      stale = true;
      console.error(`generated file is stale: ${relative(tsRoot, output)}`);
    }
  } else {
    writeFileSync(output, generated);
  }
}
if (stale) process.exitCode = 1;

function render(schema, prefix, sourcePath) {
  const definitions = schema.$defs ?? {};
  const lines = [
    `// Code generated by scripts/generate-schema-types.mjs from ${sourcePath}; DO NOT EDIT.`,
    "",
    `export const ${prefix}SchemaId = ${JSON.stringify(schema.$id)} as const;`,
    `export const ${prefix}SchemaTitle = ${JSON.stringify(schema.title)} as const;`,
    "",
    `export type ${prefix}SchemaDocument = ${schemaType(schema, prefix)};`,
    "",
  ];
  for (const [name, definition] of Object.entries(definitions)) {
    const typeName = `${prefix}Schema${pascal(name)}`;
    if (definition.type === "object" || definition.properties !== undefined) {
      lines.push(`export interface ${typeName} {`);
      const required = new Set(definition.required ?? []);
      for (const [property, propertySchema] of Object.entries(
        definition.properties ?? {},
      ))
        lines.push(
          `  readonly ${quotedProperty(property)}${required.has(property) ? "" : "?"}: ${schemaType(propertySchema, prefix)};`,
        );
      if (
        definition.additionalProperties &&
        typeof definition.additionalProperties === "object"
      )
        lines.push(
          `  readonly [key: string]: ${schemaType(definition.additionalProperties, prefix)};`,
        );
      lines.push("}", "");
    } else {
      lines.push(
        `export type ${typeName} = ${schemaType(definition, prefix)};`,
        "",
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

function schemaType(schema, prefix) {
  if (schema === true || schema === undefined) return "unknown";
  if (schema === false) return "never";
  if (schema.$ref) {
    if (schema.$ref.startsWith("#/$defs/"))
      return `${prefix}Schema${pascal(schema.$ref.split("/").at(-1))}`;
    return "unknown";
  }
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return schema.enum.map(literal).join(" | ");
  if (schema.oneOf || schema.anyOf)
    return (schema.oneOf ?? schema.anyOf)
      .map((item) => schemaType(item, prefix))
      .join(" | ");
  if (schema.type === "array")
    return `readonly (${schemaType(schema.items, prefix)})[]`;
  if (schema.type === "object" || schema.properties !== undefined)
    return objectShape(schema, prefix);
  if (schema.type === "string") return "string";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "number" || schema.type === "integer") return "number";
  if (Array.isArray(schema.type))
    return schema.type.map((type) => schemaType({ type }, prefix)).join(" | ");
  return "unknown";
}
function objectShape(schema, prefix) {
  const required = new Set(schema.required ?? []);
  const members = Object.entries(schema.properties ?? {}).map(
    ([name, value]) =>
      "readonly " +
      quotedProperty(name) +
      (required.has(name) ? "" : "?") +
      ": " +
      schemaType(value, prefix) +
      ";",
  );
  if (
    schema.additionalProperties &&
    typeof schema.additionalProperties === "object"
  )
    members.push(
      "readonly [key: string]: " +
        schemaType(schema.additionalProperties, prefix) +
        ";",
    );
  return "{ " + members.join(" ") + " }";
}
function literal(value) {
  return typeof value === "string" ? JSON.stringify(value) : String(value);
}
function pascal(value) {
  return value
    .replace(/[^A-Za-z0-9]+(.)?/g, (_, character) =>
      character ? character.toUpperCase() : "",
    )
    .replace(/^./, (character) => character.toUpperCase());
}
function quotedProperty(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value)
    ? value
    : JSON.stringify(value);
}
